const starters = ['😀', '😂', '🥰', '😍', '👍', '🙏', '❤️', '🔥', '🎉', '👏', '😊', '😭'];
let recent = [...starters];
const listeners = new Set();

export function recentEmojis() {
  return recent;
}

export function rememberEmoji(emoji) {
  recent = [emoji, ...recent.filter((item) => item !== emoji)].slice(0, 32);
  listeners.forEach((listener) => listener(recent));
}

export function subscribeRecent(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}
